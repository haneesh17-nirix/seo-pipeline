import 'dotenv/config';
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join } from 'path';
import { runPipeline, brandContextFrom, FORMAT_DURATIONS } from './pipeline';
import type { Brief } from './types';

/**
 * Runs the agent chain and writes the result.
 *
 * Output goes to brands/<slug>/output/agent-scripts/ rather than the existing
 * videos/ directory, so the new pipeline can be compared against the old corpus
 * instead of overwriting it.
 *
 *   npx ts-node src/agents/run.ts sahayi "emergency plumber in Kochi" short English
 */

async function main() {
  const [slug, keyword, formatArg, languageArg] = process.argv.slice(2);

  if (!slug || !keyword) {
    console.error('usage: run.ts <brand-slug> "<keyword>" [format] [language]');
    console.error('  format:   short | reel | ad-15s | ad-30s | explainer-60s   (default short)');
    console.error('  language: English | Manglish | Malayalam | Hindi           (default English)');
    process.exit(1);
  }

  const format = (formatArg ?? 'short') as Brief['format'];
  const language = (languageArg ?? 'English') as Brief['language'];

  const raw = JSON.parse(readFileSync(`brands/${slug}/brand.json`, 'utf8'));
  const brand = brandContextFrom(raw);

  const brief: Brief = {
    keyword,
    format,
    targetDuration: FORMAT_DURATIONS[format] ?? 59,
    location: brand.places[0],
    language,
  };

  console.log(`\n  ${brand.name} · ${keyword}`);
  console.log(`  ${format} · ${brief.targetDuration}s · ${language}`);
  console.log(`  model: ${process.env.AGENT_MODEL ?? process.env.OLLAMA_MODEL ?? 'qwen2.5:7b'}\n`);

  const result = await runPipeline(brief, brand, {
    withShotList: true,
    onProgress: (stage, detail) =>
      console.log(`  ${stage.padEnd(13)} ${detail ?? ''}`),
  });

  console.log(`\n  ${'─'.repeat(60)}`);
  console.log(`  revisions   ${result.revisions}`);
  console.log(`  validator   ${result.passed ? '✓ passed' : '✗ failed'}`);
  for (const e of result.errors) console.log(`      ERROR  ${e}`);
  for (const w of result.warnings) console.log(`      warn   ${w}`);
  console.log(`  elapsed     ${(result.elapsedMs / 1000).toFixed(1)}s`);

  const last = result.critiques[result.critiques.length - 1];
  if (last?.scores) {
    console.log(`  final score ${Object.entries(last.scores).map(([k, v]) => `${k}=${v}`).join('  ')}`);
  }

  console.log(`\n  hook   "${result.script.hook}"`);
  console.log(`  title  ${result.script.title}`);
  console.log(`  scenes ${result.script.scenes.map((s) => s.durationSeconds).join('+')} = ${
    result.script.scenes.reduce((a, s) => a + s.durationSeconds, 0)
  }s\n`);
  for (const [i, s] of result.script.scenes.entries()) {
    console.log(`   ${i + 1}. [${String(s.durationSeconds).padStart(2)}s] ${s.caption}`);
    console.log(`       “${s.voiceover}”`);
  }
  console.log(`\n  CTA    ${result.script.cta}`);
  console.log(`  tags   ${(result.script.hashtags ?? []).join(' ')}\n`);

  const dir = join('brands', slug, 'output', 'agent-scripts');
  mkdirSync(dir, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  const base = `${format}-${language.toLowerCase()}-${keyword.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}-${stamp}`;

  writeFileSync(join(dir, `${base}.json`), JSON.stringify(result, null, 2));
  writeFileSync(join(dir, `${base}.md`), toProductionScript(result));
  console.log(`  written  ${join(dir, base)}.{json,md}\n`);
}

/** Emits the same markdown shape the renderer already understands. */
function toProductionScript(r: Awaited<ReturnType<typeof runPipeline>>): string {
  const s = r.script;
  const lines = [
    `# Video Production Script — ${s.title}`,
    `**Format:** ${r.brief.format} | **Duration:** ${r.brief.targetDuration}s | **Ratio:** 9:16 | **Language:** ${r.brief.language}`,
    `**Music:** ${s.music}`,
    `**Hook (first 3s):** ${s.hook}`,
    '',
    '## Scenes',
  ];

  for (const [i, sc] of s.scenes.entries()) {
    lines.push(
      `### Scene ${i + 1} (${sc.durationSeconds}s)`,
      `**Visual:** ${sc.visualPrompt}`,
      `**Voiceover:** "${sc.voiceover}"`,
      `**On-screen text:** ${sc.caption}`,
      `**Transition:** ${sc.transition || 'cut'}`,
      '',
    );
  }

  lines.push('## CTA', '', s.cta, '', '## Hashtags', '', (s.hashtags ?? []).join(' '), '');

  if (r.shotList) {
    lines.push('---', '', '## Shot list', '');
    for (const shot of r.shotList.shots) {
      lines.push(
        `**Scene ${shot.scene}** (${shot.seconds}s) — ${shot.shotType}`,
        `- Subject: ${shot.subject}`,
        `- Action: ${shot.action}`,
        `- Render prompt: ${shot.renderPrompt}`,
        '',
      );
    }
    lines.push(`**Voice:** ${r.shotList.voiceDirection}`, '', `**Music:** ${r.shotList.musicDirection}`, '');
  }

  lines.push(
    '---',
    '',
    `Generated by the agent chain · ${r.revisions} revision(s) · validator ${r.passed ? 'passed' : 'FAILED'}`,
  );

  return lines.join('\n');
}

main().catch((err) => {
  console.error(`\n  ✗ ${err.message}\n`);
  process.exit(1);
});
